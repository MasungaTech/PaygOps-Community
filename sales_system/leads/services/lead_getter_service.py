    @classmethod
    def get_lead_for_communication_tool(cls, filters, user):
        intl = lambda l: [int(i) for i in l]
        locations = filters.get('Location', [])
        statuses = filters.get('Status', [])
        offer_types = filters.get('OfferType', [])

        if not locations or not statuses:
            leads = MockQuery([])
        else:
            leads = cls.get_list(user)
            leads = leads.filter(lambda l: l.status.category != StatusCategory.installed)
            if not 'all' in locations:
                leads = leads.filter(lambda lead: lead.person.village.parent.parent.id in intl(locations))
            if not 'all' in statuses:
                leads = leads.filter(lambda lead: lead.status.id in intl(statuses))
            if not 'all' in offer_types:
                leads_offer = leads.filter(lambda lead: lead.offer.type in offer_types)
                if 'none' in offer_types:
                    leads = leads.filter(lambda lead: lead in leads_offer or not lead.offer)
                else:
                    leads = leads_offer
        return leads