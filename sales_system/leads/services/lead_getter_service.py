    @classmethod
    def get_list_for_mobile(cls, user, cached_ids=None, **kwargs):
        generated_leads = []
        created_leads = []
        leads = orm.select(l.id for l in cls.get_leads_with_permission(user, 'SyncLeadsMobile', for_sync=True))[:]
        if user.can_access('SyncAllGeneratedLeadsMobile'):
            generated_leads = orm.select(l.id for l in cls.get_leads_generated_by_user(user))[:]
        if user.can_access('SyncAllCreatedLeadsMobile'):
            created_leads = orm.select(l.id for l in cls.get_leads_created_by(user))[:]
        leads = orm.select(l for l in Lead if l.id in leads+generated_leads+created_leads)

        date_15_days = datetime.today() - timedelta(days=15)
        date_60_days = datetime.today() - timedelta(days=60)
        date_365_days = datetime.today() - timedelta(days=365)
        installed_last_12_months_villages = [v.id for v in user.get_entities_with_permission('SyncInstalledLast12MonthsLeadsMobile', level=0, for_sync=True)]
        installedInLast12months = orm.select(l.id for l in leads if l.person.village.id in installed_last_12_months_villages
                                            and l.installed and l.contract and l.contract.start_time >= date_365_days)[:]
        installed_last_2_months_villages = [v.id for v in user.get_entities_with_permission('SyncInstalledLast2MonthsLeadsMobile', level=0, for_sync=True)]
        installedInLast2months = orm.select(l.id for l in leads if l.person.village.id in installed_last_2_months_villages
                                            and l.installed and l.contract and l.contract.start_time >= date_60_days)[:]
        installed_last_2_weeks_villages = [v.id for v in user.get_entities_with_permission('SyncInstalledLast2WeeksLeadsMobile', level=0, for_sync=True)]
        installedInLast2weeks = orm.select(l.id for l in leads if l.person.village.id in installed_last_2_weeks_villages 
                                            and l.installed and l.contract and l.contract.start_time >= date_15_days)[:]
        leads = leads.filter(lambda l: (not l.installed and not l.discarded)
                                or l.id in installedInLast12months+installedInLast2months+installedInLast2weeks)
        return leads

